export function bengaliToEnglish(input) {
    
  const map = {
    'অ': 'a', 'আ': 'aa', 'ই': 'i', 'ঈ': 'ii', 'উ': 'u', 'ঊ': 'uu',
    'ঋ': 'ri', 'এ': 'e', 'ঐ': 'oi', 'ও': 'o', 'ঔ': 'ou',
    'ক': 'k', 'খ': 'kh', 'গ': 'g', 'ঘ': 'gh', 'ঙ': 'ng',
    'চ': 'ch', 'ছ': 'chh', 'জ': 'j', 'ঝ': 'jh', 'ঞ': 'n',
    'ট': 't', 'ঠ': 'th', 'ড': 'd', 'ঢ': 'dh', 'ণ': 'n',
    'ত': 't', 'থ': 'th', 'দ': 'd', 'ধ': 'dh', 'ন': 'n',
    'প': 'p', 'ফ': 'ph', 'ব': 'b', 'ভ': 'bh', 'ম': 'm',
    'য': 'ju', 'র': 'r', 'ল': 'l', 'শ': 'sh', 'ষ': 'ss', 'স': 's', 'হ': 'h',
    'ড়': 'r', 'ঢ়': 'rh', 'য়': 'y', 'ৎ': 't', '্': 'a',

    // Special characters
    'ঽ': "'", '্র': 'r', '্য': 'y',

    // Numbers
    '০': '0', '১': '1', '২': '2', '৩': '3', '৪': '4',
    '৫': '5', '৬': '6', '৭': '7', '৮': '8', '৯': '9',

    // Vowel signs (matra)
    'া': 'a', 'ি': 'i', 'ী': 'ii', 'ু': 'u', 'ূ': 'uu',
    'ে': 'ae', 'ৈ': 'oi', 'ো': 'o', 'ৌ': 'ou', '়': 'a',

    // Other signs
    'ং': 'ng', 'ঃ': 'h', 'ঁ': 'n' , '্': 'a' // Virama
  };

  return input.split('').map(ch => map[ch] || ch).join('');
}
